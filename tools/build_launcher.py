"""Build UltraInstinctTearsLauncher.exe: the settings launcher (launcher/, Dear ImGui on SDL3's renderer).

usage: py -3 tools/build_launcher.py [-j N]                       (Windows: MSYS2 CLANG64, as tools/build_game.py)
       python3 tools/build_launcher.py --cxx CMD --sdl PREFIX [--target linux|windows] [--rc CMD] [--out FILE]
                                                                  (any other compiler, e.g. a Linux test build)
tools/setup.py runs it after the game compiles. It needs no game files: the schema (launcher/settings.ini) and the
fonts (third_party/inter) are compiled into the exe, so the launcher is one file next to UltraInstinctTears.exe.
Checks first that the schema covers every key the game reads (tools/check_launcher_keys.py).
"""
import argparse
import concurrent.futures
import os
import pathlib
import shlex
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import version  # noqa: E402

SOURCES = ['launcher/main.cpp', 'launcher/model.cpp', 'launcher/platform.cpp', 'launcher/save_backup.cpp', 'launcher/single_instance.cpp', 'launcher/ui.cpp', 'launcher/modfs_cxx.cpp',
           'third_party/imgui/imgui.cpp', 'third_party/imgui/imgui_draw.cpp', 'third_party/imgui/imgui_tables.cpp',
           'third_party/imgui/imgui_widgets.cpp', 'third_party/imgui/backends/imgui_impl_sdl3.cpp',
           'third_party/imgui/backends/imgui_impl_sdlrenderer3.cpp']
EMBED = [('kSettingsIni', 'launcher/settings.ini'), ('kInterRegular', 'third_party/inter/Inter-Regular.ttf'),
         ('kInterSemiBold', 'third_party/inter/Inter-SemiBold.ttf'), ('kUitIconPng', 'assets/uit-256.png')]
# No C++ standard library: launcher/mini.h has the bits the launcher uses and Dear ImGui needs only C headers, so the
# build works with a toolchain whose libc++ headers are missing or partial (the builder package's trimmed CLANG64).
# Without exceptions, RTTI or thread-safe statics the objects need nothing from libc++ either (-nostdlib++).
CXXFLAGS = ['-std=c++17', '-O2', '-nostdinc++', '-fno-exceptions', '-fno-rtti', '-fno-threadsafe-statics',
            '-DIMGUI_DISABLE_DEMO_WINDOWS', '-DIMGUI_DISABLE_DEBUG_TOOLS', '-Ithird_party/imgui', '-Ilauncher',
            '-Ibuild/launcher']
NO_CXX_LIB = ['-nostdlib++']
# the static SDL3 also needs iconv; its CM_* (device) calls resolve from libsetupapi.a (the builder package has no
# libcfgmgr32.a, and MinGW's setupapi import library carries them too). The GUI subsystem is a linker flag, not
# -mwindows: clang's -mwindows also adds -lcomdlg32, which the builder package does not have either.
WIN_LIBS = ['-static', '-Wl,--subsystem,windows', '-lSDL3', '-liconv', '-luser32', '-lgdi32', '-limm32', '-lole32', '-loleaut32',
            '-lversion', '-luuid', '-ladvapi32', '-lsetupapi', '-lshell32', '-lwinmm', '-ldinput8', '-lbcrypt']


def write_if_changed(path, data):
    if not path.is_file() or path.read_bytes() != data:
        path.write_bytes(data)


def embed(build):
    """build/launcher/launcher_data.h: the schema and fonts as byte arrays (the schema with a terminating 0)."""
    out = ['// generated by tools/build_launcher.py from launcher/settings.ini and third_party/inter: do not edit', '#pragma once',
           '#include <stddef.h>']
    for name, src in EMBED:
        data = (ROOT / src).read_bytes()
        rows = [','.join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32)]
        out.append(f'static const unsigned char {name}[] = {{\n' + ',\n'.join(rows) + ',0};')
        out.append(f'static const size_t {name}Size = {len(data)};')
    write_if_changed(build / 'launcher_data.h', ('\n'.join(out) + '\n').encode())


def rc_file(build):
    v, commit = version.current()
    n = ','.join(str(x) for x in version.numbers(v))
    text = f'''1 ICON "assets/uit.ico"
1 VERSIONINFO
FILEVERSION {n}
PRODUCTVERSION {n}
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "CompanyName", "Ultra Instinct Tears contributors (based on UltraTears by kuraeow)"
      VALUE "FileDescription", "Ultra Instinct Tears Launcher"
      VALUE "FileVersion", "{v} ({commit})"
      VALUE "LegalCopyright", "GPL-3.0-or-later. Not affiliated with Nintendo."
      VALUE "OriginalFilename", "UltraInstinctTearsLauncher.exe"
      VALUE "ProductName", "Ultra Instinct Tears"
      VALUE "ProductVersion", "{v}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
'''
    write_if_changed(build / 'launcher.rc', text.encode())
    write_if_changed(build / 'version.h', f'#define ULTRS_VERSION "{v}"\n#define ULTRS_COMMIT "{commit}"\n'.encode())
    return v


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--cxx', help='C++ compiler command (default: CLANG64 clang in g++ mode)')
    ap.add_argument('--sdl', help='an SDL3 install prefix (include/, lib/libSDL3.a); default: the compiler\'s own')
    ap.add_argument('--target', choices=('windows', 'linux'), default='windows' if os.name == 'nt' else 'linux')
    ap.add_argument('--rc', help='resource compiler command for --target windows (default: llvm-windres; "none": no icon)')
    ap.add_argument('--out', help='output file (default: UltraInstinctTearsLauncher.exe in the game folder)')
    ap.add_argument('-j', type=int, default=os.cpu_count() or 4)
    a = ap.parse_args()

    rc = subprocess.run([sys.executable, str(ROOT / 'tools/check_launcher_keys.py')], cwd=ROOT).returncode
    if rc:
        sys.exit('the launcher schema does not match the game\'s keys: fix launcher/settings.ini')

    build = ROOT / 'build' / 'launcher'
    (build / 'obj').mkdir(parents=True, exist_ok=True)
    embed(build)
    win = a.target == 'windows'
    env = None
    if a.cxx:
        cxx = shlex.split(a.cxx)
    else:
        from toolchain import CLANG64, env as tool_env
        env = tool_env()
        cxx = [str(CLANG64 / 'clang.exe'), '--driver-mode=g++']
    flags = CXXFLAGS + (['-I' + str(pathlib.Path(a.sdl) / 'include')] if a.sdl else [])
    v = rc_file(build)
    print(f'Ultra Instinct Tears Launcher {v} ({a.target})', flush=True)

    deps = [ROOT / p for p in ('launcher/mini.h', 'launcher/model.h', 'launcher/platform.h', 'launcher/ui.h', 'build/launcher/launcher_data.h',
                               'build/launcher/version.h', 'third_party/imgui/imgui.h', 'third_party/imgui/imconfig.h',
                               'third_party/imgui/imgui_internal.h')]
    newest_dep = max(p.stat().st_mtime for p in deps)
    stamp = build / 'obj' / 'flags.txt'
    sig = ' '.join(cxx + flags)
    fresh = stamp.is_file() and stamp.read_text() == sig
    stamp.write_text(sig)

    def compile_one(src):
        obj = build / 'obj' / (pathlib.Path(src).stem + '.o')
        s = ROOT / src
        if fresh and obj.is_file() and obj.stat().st_mtime >= max(s.stat().st_mtime, newest_dep if src.startswith('launcher') else 0):
            return obj, 0, ''
        p = subprocess.run(cxx + flags + ['-c', src, '-o', str(obj)], cwd=ROOT, env=env, capture_output=True, text=True,
                           stdin=subprocess.DEVNULL)
        return obj, p.returncode, p.stdout + p.stderr

    objs, failed = [], False
    with concurrent.futures.ThreadPoolExecutor(max(1, a.j)) as pool:
        for src, (obj, code, log) in zip(SOURCES, pool.map(compile_one, SOURCES)):
            if log.strip():
                print(f'--- {src}\n{log}', flush=True)
            failed |= code != 0
            objs.append(str(obj))
    if failed:
        sys.exit('compiling the launcher failed (see above)')

    out = pathlib.Path(a.out) if a.out else ROOT / ('UltraInstinctTearsLauncher.exe' if win else 'build/launcher/ultrainstincttears-launcher')
    if win and a.rc != 'none':
        res = build / 'obj' / 'launcher_res.o'
        # The icon and version info are optional: a missing or failing resource compiler only skips them.
        import shutil
        rc_cmd = shlex.split(a.rc) if a.rc else None
        if rc_cmd is None:
            path = env.get('PATH', os.environ.get('PATH', '')) if isinstance(env, dict) else os.environ.get('PATH', '')
            for name in ('llvm-windres', 'x86_64-w64-mingw32-windres', 'windres'):
                exe = shutil.which(name, path=path)
                if exe:
                    rc_cmd = [exe] + (['--target=pe-x86-64'] if 'llvm' in name else [])
                    break
        ok = False
        if rc_cmd:
            try:
                r = subprocess.run(rc_cmd + ['-I', '.', str(build / 'launcher.rc'), '-o', str(res)], cwd=ROOT, env=env)
                ok = r.returncode == 0 and res.is_file()
            except OSError as e:
                print(f'  note: resource compiler not usable ({e})', flush=True)
        if ok:
            objs.append(str(res))
        else:
            print('  note: no resource compiler found, so the launcher is built without its icon and version info (it works the same)', flush=True)
    if win:
        link = cxx + (['-fuse-ld=lld'] if not a.cxx else []) + NO_CXX_LIB + ['-o', str(out)] + objs
        link += (['-L' + str(pathlib.Path(a.sdl) / 'lib')] if a.sdl else []) + WIN_LIBS
    else:
        link = cxx + NO_CXX_LIB + ['-o', str(out)] + objs
        link += [str(pathlib.Path(a.sdl) / 'lib/libSDL3.a')] if a.sdl else ['-lSDL3']
        link += ['-lpthread', '-lm', '-ldl']
    r = subprocess.run(link, cwd=ROOT, env=env)
    if r.returncode:
        sys.exit('linking the launcher failed')
    print(f'{out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}: {out.stat().st_size // 1024} KB', flush=True)


if __name__ == '__main__':
    main()
