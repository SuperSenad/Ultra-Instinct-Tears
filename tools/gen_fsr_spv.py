#!/usr/bin/env python3
"""Compile src/vk/shaders/* to SPIR-V and write src/vk/fsr1_spv.h, dlss_mv_spv.h and overlay_spv.h (uint32_t arrays).

The game build (tools/build_game.py) has no shader compiler, so the generated header is committed; run this only
after changing a shader:  python tools/gen_fsr_spv.py [path/to/glslang]   (glslang or glslangValidator on PATH).
"""
import os, shutil, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADERS = [
    ("src/vk/fsr1_spv.h", "src/vk/shaders/fsr1_*.comp", "FSR 1 (EASU, RCAS): AMD FidelityFX Super Resolution 1.0, MIT (notice in fsr1_easu.comp).",
     [("fsr1_easu_spv", "src/vk/shaders/fsr1_easu.comp"), ("fsr1_rcas_spv", "src/vk/shaders/fsr1_rcas.comp")]),
    ("src/vk/dlss_mv_spv.h", "src/vk/shaders/dlss_mv.comp", "Camera motion vectors for DLSS (src/gfx/vkb_dlss.c).",
     [("dlss_mv_spv", "src/vk/shaders/dlss_mv.comp")]),
    ("src/vk/overlay_spv.h", "src/vk/shaders/overlay.*", "The in-game overlay's quads (src/vk/overlay_vk.c) [UIT 0172].",
     [("overlay_vert_spv", "src/vk/shaders/overlay.vert"), ("overlay_frag_spv", "src/vk/shaders/overlay.frag")]),
]


def main():
    glslang = sys.argv[1] if len(sys.argv) > 1 else shutil.which("glslang") or shutil.which("glslangValidator")
    if not glslang:
        sys.exit("glslang not found (Vulkan SDK, or https://github.com/KhronosGroup/glslang/releases)")
    for header, what, note, shaders in HEADERS:
        out = ["// Generated by tools/gen_fsr_spv.py from %s -- do not edit." % what, "// " + note,
               "#pragma once", "#include <stdint.h>", ""]
        with tempfile.TemporaryDirectory() as tmp:
            for name, src in shaders:
                spv = os.path.join(tmp, name + ".spv")
                subprocess.run([glslang, "-V", "--target-env", "vulkan1.3", os.path.join(ROOT, src), "-o", spv], check=True)
                data = open(spv, "rb").read()
                words = struct.unpack("<%dI" % (len(data) // 4), data)
                out.append("static const uint32_t %s[%d] = {" % (name, len(words)))
                for i in range(0, len(words), 8):
                    out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
                out.append("};")
                out.append("")
        with open(os.path.join(ROOT, header), "w", newline="\n") as f:
            f.write("\n".join(out))


if __name__ == "__main__":
    main()
