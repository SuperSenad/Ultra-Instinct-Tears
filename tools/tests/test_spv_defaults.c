// the words after the rewrite: OpStore of a new output at the entry's start, before the first original instruction
static int count_op(const uint32_t *w, size_t n, uint32_t op) {
    int c = 0;
    for (size_t i = 5; i < n;) { uint32_t wc = w[i] >> 16; if (!wc) return -1; if ((w[i] & 0xffff) == op) c++; i += wc; }
    return c;
}
static void one(const char *name, const uint32_t *in, unsigned len, const char *dir) {
    size_t nw = len / 4;
    uint32_t fs_reads = vkb_spv_input_mask((const uint32_t *)fs_spv, fs_spv_len / 4);
    uint32_t fs_f4 = vkb_spv_input_f4_mask((const uint32_t *)fs_spv, fs_spv_len / 4);
    CHECK(fs_reads == 0xb);
    CHECK(fs_f4 == 0x3);   // the ivec4 at 3 is not given a default
    uint32_t vs_out = vkb_spv_output_mask(in, nw);
    CHECK(vs_out == 0x5);
    uint32_t defs = fs_reads & ~vs_out & fs_f4;
    CHECK(defs == 0x2);
    uint32_t *o = NULL; size_t on = 0;
    CHECK(vkb_spv_default_outputs(in, nw, defs, &o, &on) == 1);
    if (!o) return;
    CHECK(vkb_spv_output_mask(o, on) == 0x7);
    CHECK(o[3] == in[3] + 5);   // bound: pointer type, 2 constants, the vector constant, 1 variable
    CHECK(count_op(o, on, 62) == count_op(in, nw, 62) + 1);   // one more OpStore
    // composed with the integer-input rewrite, as the variant does
    uint32_t *o2 = NULL; size_t on2 = 0;
    CHECK(vkb_spv_int_inputs(o, on, 0x1, 0, &o2, &on2) == 1);
    CHECK(o2 && vkb_spv_output_mask(o2, on2) == 0x7);
    // nothing to add, or a location mask of 0: no module
    uint32_t *o3 = NULL; size_t on3 = 0;
    CHECK(vkb_spv_default_outputs(in, nw, 0, &o3, &on3) == 0 && !o3);
    if (dir) {
        char p[512];
        snprintf(p, sizeof p, "%s/%s-def.spv", dir, name);
        FILE *f = fopen(p, "wb"); if (f) { fwrite(o, 4, on, f); fclose(f); }
    }
    free(o); free(o2);
}

int main(int argc, char **argv) {
    one("vs10", vs10_spv, vs10_spv_len, argc > 1 ? argv[1] : NULL);
    one("vs13", vs13_spv, vs13_spv_len, argc > 1 ? argv[1] : NULL);
    printf(fails ? "%d FAILED\n" : "all passed\n", fails);
    return fails != 0;
}
