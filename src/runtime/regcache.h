// [UIT 0078] Flags kept in a C local (tools/lifter/regcache.py): the cpu.h flag helpers and conditions, on a value.
// Code lifted with the register cache keeps NZCV in `rc_nz` and the hottest general registers in `rc_x<n>` / `rc_sp`
// between calls; these are cpu.h's adds64 / COND_EQ / ... with the flags passed by name instead of through Cpu.
// Each must compute exactly what its cpu.h original does (tools/tests/test_regcache.py runs both).
#pragma once
#include "cpu.h"

#define RCF_N(f) (((f) >> 31) & 1)
#define RCF_Z(f) (((f) >> 30) & 1)
#define RCF_C(f) (((f) >> 29) & 1)
#define RCF_V(f) (((f) >> 28) & 1)
#define RCOND_EQ(f) (RCF_Z(f))
#define RCOND_NE(f) (!RCF_Z(f))
#define RCOND_CS(f) (RCF_C(f))
#define RCOND_CC(f) (!RCF_C(f))
#define RCOND_MI(f) (RCF_N(f))
#define RCOND_PL(f) (!RCF_N(f))
#define RCOND_VS(f) (RCF_V(f))
#define RCOND_VC(f) (!RCF_V(f))
#define RCOND_HI(f) (RCF_C(f) && !RCF_Z(f))
#define RCOND_LS(f) (!(RCF_C(f) && !RCF_Z(f)))
#define RCOND_GE(f) (RCF_N(f) == RCF_V(f))
#define RCOND_LT(f) (RCF_N(f) != RCF_V(f))
#define RCOND_GT(f) (!RCF_Z(f) && RCF_N(f) == RCF_V(f))
#define RCOND_LE(f) (!(!RCF_Z(f) && RCF_N(f) == RCF_V(f)))

// (statement expressions: the flags variable is assigned in place, no address is taken, so musttail stays legal)
#define RC_ADDS(N, f, a, b) ({ uint##N##_t rcA_ = (a), rcB_ = (b), rcR_ = rcA_ + rcB_; \
    (f) = MKFLAGS(rcR_ >> (N - 1), rcR_ == 0, rcR_ < rcA_, ((rcA_ ^ rcR_) & (rcB_ ^ rcR_)) >> (N - 1)); rcR_; })
#define RC_SUBS(N, f, a, b) ({ uint##N##_t rcA_ = (a), rcB_ = (b), rcR_ = rcA_ - rcB_; \
    (f) = MKFLAGS(rcR_ >> (N - 1), rcR_ == 0, rcA_ >= rcB_, ((rcA_ ^ rcB_) & (rcA_ ^ rcR_)) >> (N - 1)); rcR_; })
#define RC_LOGIC(N, f, v) ({ uint##N##_t rcR_ = (v); (f) = MKFLAGS(rcR_ >> (N - 1), rcR_ == 0, 0, 0); rcR_; })
#define RC_ADC(N, f, a, b) ((uint##N##_t)((uint##N##_t)(a) + (uint##N##_t)(b) + (uint##N##_t)RCF_C(f)))
#define RC_SBC(N, f, a, b) ((uint##N##_t)((uint##N##_t)(a) - (uint##N##_t)(b) - 1 + (uint##N##_t)RCF_C(f)))
#define RC_ADCS(N, f, a, b) ({ uint##N##_t rcA_ = (a), rcB_ = (b), rcI_ = RCF_C(f), rcR_ = rcA_ + rcB_ + rcI_; \
    int rcY_ = rcI_ ? rcR_ <= rcA_ : rcR_ < rcA_; \
    (f) = MKFLAGS(rcR_ >> (N - 1), rcR_ == 0, rcY_, ((rcA_ ^ rcR_) & (rcB_ ^ rcR_)) >> (N - 1)); rcR_; })
#define rc_adds64(f, a, b) RC_ADDS(64, f, a, b)
#define rc_adds32(f, a, b) RC_ADDS(32, f, a, b)
#define rc_subs64(f, a, b) RC_SUBS(64, f, a, b)
#define rc_subs32(f, a, b) RC_SUBS(32, f, a, b)
#define rc_logic64(f, v) RC_LOGIC(64, f, v)
#define rc_logic32(f, v) RC_LOGIC(32, f, v)
#define rc_adc64(f, a, b) RC_ADC(64, f, a, b)
#define rc_adc32(f, a, b) RC_ADC(32, f, a, b)
#define rc_sbc64(f, a, b) RC_SBC(64, f, a, b)
#define rc_sbc32(f, a, b) RC_SBC(32, f, a, b)
#define rc_adcs64(f, a, b) RC_ADCS(64, f, a, b)
#define rc_adcs32(f, a, b) RC_ADCS(32, f, a, b)
#define rc_sbcs64(f, a, b) RC_ADCS(64, f, a, (uint64_t)~(uint64_t)(b))
#define rc_sbcs32(f, a, b) RC_ADCS(32, f, a, (uint32_t)~(uint32_t)(b))

// [UIT 0084] Flags as operands (TOTK_LIFT_REGCACHE_FLAGS=1, regcache.py): a flag-setting subs / adds / ands keeps
// its operands (or result) in the locals rc_fa / rc_fb instead of packing NZCV, and a condition that only those can
// reach is computed straight from them (b.lt after cmp: one signed compare). rco_*: operands only; rcob_*: operands
// and the packed flags (when the same flags are also read packed elsewhere); RCPK_*: the packed flags from the
// operands, at a write-back. Each must equal the cpu.h original (tools/tests/test_regcache.py runs both).
#define RCO_SUBS(N, fa, fb, a, b) ({ uint##N##_t rcoA_ = (a), rcoB_ = (b); (fa) = rcoA_; (fb) = rcoB_; (uint##N##_t)(rcoA_ - rcoB_); })
#define RCO_ADDS(N, fa, fb, a, b) ({ uint##N##_t rcoA_ = (a), rcoB_ = (b); (fa) = rcoA_; (fb) = rcoB_; (uint##N##_t)(rcoA_ + rcoB_); })
#define RCO_LOGIC(N, fa, v) ({ uint##N##_t rcoR_ = (v); (fa) = rcoR_; rcoR_; })
#define RCOB_SUBS(N, f, fa, fb, a, b) ({ uint##N##_t rcoA_ = (a), rcoB_ = (b); (fa) = rcoA_; (fb) = rcoB_; RC_SUBS(N, f, rcoA_, rcoB_); })
#define RCOB_ADDS(N, f, fa, fb, a, b) ({ uint##N##_t rcoA_ = (a), rcoB_ = (b); (fa) = rcoA_; (fb) = rcoB_; RC_ADDS(N, f, rcoA_, rcoB_); })
#define RCOB_LOGIC(N, f, fa, v) ({ uint##N##_t rcoR_ = (v); (fa) = rcoR_; RC_LOGIC(N, f, rcoR_); })
#define RCPK_SUBS(N, a, b) ({ uint64_t rcoF_; (void)RC_SUBS(N, rcoF_, (a), (b)); rcoF_; })
#define RCPK_ADDS(N, a, b) ({ uint64_t rcoF_; (void)RC_ADDS(N, rcoF_, (a), (b)); rcoF_; })
#define RCPK_LOGIC(N, r) ({ uint64_t rcoF_; (void)RC_LOGIC(N, rcoF_, (r)); rcoF_; })
#define rco_subs64(fa, fb, a, b) RCO_SUBS(64, fa, fb, a, b)
#define rcob_subs64(f, fa, fb, a, b) RCOB_SUBS(64, f, fa, fb, a, b)
#define RCPK_SUBS64(a, b) RCPK_SUBS(64, a, b)
#define rco_adds64(fa, fb, a, b) RCO_ADDS(64, fa, fb, a, b)
#define rcob_adds64(f, fa, fb, a, b) RCOB_ADDS(64, f, fa, fb, a, b)
#define RCPK_ADDS64(a, b) RCPK_ADDS(64, a, b)
#define rco_logic64(fa, v) RCO_LOGIC(64, fa, v)
#define rcob_logic64(f, fa, v) RCOB_LOGIC(64, f, fa, v)
#define RCPK_LOGIC64(r) RCPK_LOGIC(64, r)
#define rco_subs32(fa, fb, a, b) RCO_SUBS(32, fa, fb, a, b)
#define rcob_subs32(f, fa, fb, a, b) RCOB_SUBS(32, f, fa, fb, a, b)
#define RCPK_SUBS32(a, b) RCPK_SUBS(32, a, b)
#define rco_adds32(fa, fb, a, b) RCO_ADDS(32, fa, fb, a, b)
#define rcob_adds32(f, fa, fb, a, b) RCOB_ADDS(32, f, fa, fb, a, b)
#define RCPK_ADDS32(a, b) RCPK_ADDS(32, a, b)
#define rco_logic32(fa, v) RCO_LOGIC(32, fa, v)
#define rcob_logic32(f, fa, v) RCOB_LOGIC(32, f, fa, v)
#define RCPK_LOGIC32(r) RCPK_LOGIC(32, r)
// conditions after subs (a - b): unsigned / signed compares of the operands
#define RCO_U(N, x) ((uint##N##_t)(x))
#define RCO_S(N, x) ((int##N##_t)(uint##N##_t)(x))
#define RCO_SV(N, a, b) ((((RCO_U(N, a) ^ RCO_U(N, b)) & (RCO_U(N, a) ^ (uint##N##_t)(RCO_U(N, a) - RCO_U(N, b)))) >> (N - 1)) & 1)
#define RCO_AV(N, a, b) ((((RCO_U(N, a) ^ (uint##N##_t)(RCO_U(N, a) + RCO_U(N, b))) & (RCO_U(N, b) ^ (uint##N##_t)(RCO_U(N, a) + RCO_U(N, b)))) >> (N - 1)) & 1)
#define RCO_W64(x) ((__int128)RCO_S(64, x))
#define RCO_W32(x) ((int64_t)RCO_S(32, x))
#define RCOS_EQ64(a, b) (RCO_U(64, a) == RCO_U(64, b))
#define RCOS_NE64(a, b) (RCO_U(64, a) != RCO_U(64, b))
#define RCOS_CS64(a, b) (RCO_U(64, a) >= RCO_U(64, b))
#define RCOS_CC64(a, b) (RCO_U(64, a) < RCO_U(64, b))
#define RCOS_MI64(a, b) (RCO_S(64, (a) - (b)) < 0)
#define RCOS_PL64(a, b) (RCO_S(64, (a) - (b)) >= 0)
#define RCOS_VS64(a, b) (RCO_SV(64, a, b))
#define RCOS_VC64(a, b) (!RCO_SV(64, a, b))
#define RCOS_HI64(a, b) (RCO_U(64, a) > RCO_U(64, b))
#define RCOS_LS64(a, b) (RCO_U(64, a) <= RCO_U(64, b))
#define RCOS_GE64(a, b) (RCO_S(64, a) >= RCO_S(64, b))
#define RCOS_LT64(a, b) (RCO_S(64, a) < RCO_S(64, b))
#define RCOS_GT64(a, b) (RCO_S(64, a) > RCO_S(64, b))
#define RCOS_LE64(a, b) (RCO_S(64, a) <= RCO_S(64, b))
#define RCOA_EQ64(a, b) ((uint64_t)(RCO_U(64, a) + RCO_U(64, b)) == 0)
#define RCOA_NE64(a, b) ((uint64_t)(RCO_U(64, a) + RCO_U(64, b)) != 0)
#define RCOA_CS64(a, b) ((uint64_t)(RCO_U(64, a) + RCO_U(64, b)) < RCO_U(64, a))
#define RCOA_CC64(a, b) ((uint64_t)(RCO_U(64, a) + RCO_U(64, b)) >= RCO_U(64, a))
#define RCOA_MI64(a, b) (RCO_S(64, (a) + (b)) < 0)
#define RCOA_PL64(a, b) (RCO_S(64, (a) + (b)) >= 0)
#define RCOA_VS64(a, b) (RCO_AV(64, a, b))
#define RCOA_VC64(a, b) (!RCO_AV(64, a, b))
#define RCOA_HI64(a, b) ((uint64_t)(RCO_U(64, a) + RCO_U(64, b)) < RCO_U(64, a) && (uint64_t)(RCO_U(64, a) + RCO_U(64, b)) != 0)
#define RCOA_LS64(a, b) (!((uint64_t)(RCO_U(64, a) + RCO_U(64, b)) < RCO_U(64, a) && (uint64_t)(RCO_U(64, a) + RCO_U(64, b)) != 0))
#define RCOA_GE64(a, b) ((RCO_W64(a) + RCO_W64(b)) >= 0)
#define RCOA_LT64(a, b) ((RCO_W64(a) + RCO_W64(b)) < 0)
#define RCOA_GT64(a, b) ((RCO_W64(a) + RCO_W64(b)) > 0)
#define RCOA_LE64(a, b) ((RCO_W64(a) + RCO_W64(b)) <= 0)
#define RCOL_EQ64(r) (RCO_U(64, r) == 0)
#define RCOL_NE64(r) (RCO_U(64, r) != 0)
#define RCOL_CS64(r) ((void)(r), 0)
#define RCOL_CC64(r) ((void)(r), 1)
#define RCOL_MI64(r) (RCO_S(64, r) < 0)
#define RCOL_PL64(r) (RCO_S(64, r) >= 0)
#define RCOL_VS64(r) ((void)(r), 0)
#define RCOL_VC64(r) ((void)(r), 1)
#define RCOL_HI64(r) ((void)(r), 0)
